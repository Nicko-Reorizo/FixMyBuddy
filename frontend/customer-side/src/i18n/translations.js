export function setActiveLanguage(language) { activeLanguage = language === 'fil' ? 'fil' : 'en'; }
export function tr(text) { return activeLanguage === 'fil' && typeof text === 'string' ? filipino[text] || text : text; }
export function trTemplate(parts, values) {
  const key = parts.map((part,index) => part + (index < values.length ? '{' + index + '}' : '')).join('');
  const pattern = activeLanguage === 'fil' ? filipino[key] || key : key;
  return pattern.replace(/\{(\d+)\}/g, (_,index) => String(values[Number(index)] ?? ''));
}

